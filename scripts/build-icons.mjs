// Writes public/student/icons.js (served at /icons.js): the Lucide icons the app uses, under the app's
// own names, and window.BQIcons.svg(name, size) to draw one. The app has no build step, so the file is
// committed; to add an icon, add its line below and run `npm run build:icons`.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import defaults from 'lucide/dist/esm/defaultAttributes.mjs';

const require = createRequire(import.meta.url);
const { icons } = require('lucide');
const { version } = require('lucide/package.json');

// The app's name for each icon: Lucide's name for it (https://lucide.dev/icons).
const NAMES = {
  // closing, confirming, moving around
  x: 'X',
  check: 'Check',
  cross: 'X', // a rubric item not met
  minus: 'Minus', // not graded yet
  up: 'ArrowUp', // sorted up
  down: 'ArrowDown', // sorted down
  back: 'ArrowLeft',
  chevron: 'ChevronDown', // opens a menu or a list
  chevronUp: 'ChevronUp',
  prev: 'ChevronLeft',
  next: 'ChevronRight',
  grip: 'GripVertical', // drag to move
  plus: 'Plus',
  dots: 'Ellipsis', // more actions
  // on buttons, before their words
  play: 'Play',
  pause: 'Pause',
  stop: 'CircleStop', // close a quiz
  reopen: 'RotateCcw',
  megaphone: 'Megaphone',
  pencil: 'Pencil', // edit; the scratchpad and its pen
  eye: 'Eye', // preview
  sliders: 'SlidersVertical', // settings
  copy: 'Copy',
  download: 'Download',
  trash: 'Trash2', // clear the scratchpad page
  sun: 'Sun',
  moon: 'Moon',
  // the teacher's sidebar
  results: 'ChartColumn',
  recent: 'History', // quizzes given lately
  braces: 'Braces', // a random value, in the quiz maker
  pool: 'Shuffle', // a question pool: each student gets some of its questions
  material: 'BookOpen', // shared material: a case or passage several questions use
  quizzes: 'FileText',
  classes: 'Users',
  teachers: 'Shield',
  live: 'Radio', // open quizzes
  warn: 'TriangleAlert', // a sign-in to check before starting
  settings: 'Settings',
  // question types (the quiz maker), and a section between them
  single: 'CircleDot',
  multi: 'SquareCheck',
  text: 'Type', // also the scratchpad's text tool
  math: 'Radical',
  graph: 'ChartSpline',
  output: 'Terminal',
  trace: 'Table',
  fill: 'TextCursorInput',
  code: 'Code',
  essay: 'TextAlignStart',
  section: 'SeparatorHorizontal',
  spark: 'Sparkles', // something an AI writes
  // the student's quiz
  person: 'User', // who's signed in
  bookmark: 'Bookmark', // mark for review
  lock: 'Lock', // a part that hasn't opened, a game not earned yet
  game: 'Gamepad2', // Play snake
  exit: 'LogOut', // leave the quiz
  eraser: 'Eraser',
  undo: 'Undo2',
  calculator: 'Calculator',
  backspace: 'Delete',
};

const shapes = {};
for (const [name, lucide] of Object.entries(NAMES)) {
  if (!icons[lucide]) throw new Error(`lucide@${version} has no icon ${lucide} (for ${name})`);
  shapes[name] = icons[lucide].map(([tag, attrs]) => [tag, attrs]);
}
const { xmlns, width, height, ...attrs } = defaults; // width and height come from each call

const license = readFileSync(new URL('../node_modules/lucide/LICENSE', import.meta.url), 'utf8').trim();
const out = `/*! Icons from Lucide (https://lucide.dev), lucide@${version}:

${license.replace(/\*\//g, '* /')}
*/
// generated by scripts/build-icons.mjs from lucide@${version}: add names there and run npm run build:icons
// BQIcons.svg(name, size, attrs): an <svg> for one of the names below, size px square (null: no size, for
// CSS to set), hidden from screen readers. attrs add to or replace Lucide's (a fill, a heavier stroke, a class).
(function () {
  'use strict';
  var NS = ${JSON.stringify(xmlns)};
  var ATTRS = ${JSON.stringify(attrs)};
  var SHAPES = {
${Object.entries(shapes).map(([n, s]) => `    ${JSON.stringify(n)}: ${JSON.stringify(s)},`).join('\n')}
  };
  // A name that isn't here is a mistake in the page's code: it stops the page in development (this computer),
  // and elsewhere is logged and drawn empty, so a student's quiz keeps working.
  var DEV = typeof location === 'object' && /^(localhost|127\\.0\\.0\\.1|\\[::1\\]|)$/.test(location.hostname);
  function has(name) { return Object.prototype.hasOwnProperty.call(SHAPES, name); }
  function svg(name, size, attrs) {
    if (!has(name)) {
      var msg = 'BQIcons: no icon named "' + name + '". Add it to scripts/build-icons.mjs and run npm run build:icons.';
      if (DEV) throw new Error(msg);
      console.error(msg);
    }
    var s = document.createElementNS(NS, 'svg');
    var all = Object.assign({}, ATTRS, size === null ? null : { width: size || ${width}, height: size || ${height} }, { 'aria-hidden': 'true' }, attrs);
    for (var k in all) if (all[k] != null) s.setAttribute(k, String(all[k]));
    (has(name) ? SHAPES[name] : []).forEach(function (shape) {
      var el = document.createElementNS(NS, shape[0]);
      for (var a in shape[1]) el.setAttribute(a, shape[1][a]);
      s.appendChild(el);
    });
    return s;
  }
  window.BQIcons = { names: Object.keys(SHAPES), has: has, svg: svg };
})();
`;
writeFileSync(new URL('../public/student/icons.js', import.meta.url), out);
console.log('icons -> public/student/icons.js (%d icons, %s KB)', Object.keys(shapes).length, (out.length / 1024).toFixed(1));
